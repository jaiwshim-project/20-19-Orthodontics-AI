#!/usr/bin/env python3
"""conversation.md 섹션 36 — 섹션 35의 원인 진단을 정정한다.

사용자가 "치아폭 정답은 원장 지도로 만든 것이라 정확도 100%"라고 알려줬다. 그 전제로
필요 폭 배율을 **폴더별로 분해**해 보니 섹션 35의 "코호트(주석자) 스케일 차" 진단이
틀렸다. 실체는 **클래스2 케이스 속성**이었다. 섹션 35를 지우지 않고 정정 섹션을 덧붙인다
(측정값 자체는 유효하고, 틀린 것은 원인 귀속이다).

conversation.md는 CRLF. 바이트로 읽고 바이트로 쓴다. 운영 HTML은 SHA만 확인한다.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONVERSATION = HERE.parent / "conversation.md"
PRODUCTION = HERE.parent / "EZ Curve - TZ Length - 보정 전 알고리즘 적용.html"
PRODUCTION_SHA = "6ee351135a8e31f9960fd1a223f65d33e50c6df9204d31e349f9a30cdf712197"

SECTION = r"""
## 36. 정정 — 스케일 차는 "주석자"가 아니라 "클래스2"였다 (2026-07-28) ⭐️⭐️

**사용자 입력**: "치아폭 찍기 정답은 원장의 지도를 받고 만든 거야. 그래서 정확도는 100%야."

이 한 문장이 섹션 35의 **원인 진단을 뒤집었다.** 35의 측정값은 전부 유효하다. 틀린 것은
**원인 귀속과 그로부터 나온 권고**다.

### 36-1. 무엇이 틀렸나

섹션 35-7은 필요 폭 배율을 "기존 268건 평균 1.071 vs 신규 116건 1.169"로 비교해
**"주석자별 코호트 스케일 차"**로 결론지었다. 그런데 "기존 268건"은 **폴더 4개가 섞인
덩어리**다. 덩어리 평균과 신규 하나를 비교했으니 두 가설을 구분할 수 없었다.

- 가설 A: 신규 폴더(유라쌤)의 주석 기준이 다르다
- 가설 B: 케이스 종류(클래스2)에 따라 다르다

원장 지도로 만든 정답이라면 A는 애초에 성립하기 어렵다. 그래서 폴더별로 분해했다
(`_cohort_scale_map.py`). 코호트는 폴더명이 아니라 **라벨 md의 SHA-256**으로 역추적했고,
산출물에는 담당자명을 남기지 않았다(익명 코드).

| 코호트 | 케이스 | 필요 폭 배율 중위수 | CI95 | 클래스2? |
|---|---:|---:|---|:--:|
| A_width_1st | 4 | 1.019 | — | 아님 |
| B_width_2nd | 52 | 1.091 | 1.072~1.134 | 아님 |
| C_postortho | 59 | 1.047 | 1.029~1.060 | 아님 |
| **D_class2_a** | 99 | **1.162** | 1.151~1.181 | **클래스2** |
| **E_class2_b** | 116 | **1.170** | 1.153~1.188 | **클래스2** |

**결정적이다.** 담당자가 **다른** D와 E가 일치하고(CI가 겹친다), 담당자가 **같은** B·C·D는
1.091 / 1.047 / 1.162로 갈린다. 즉 갈리는 축은 주석자가 아니라 **클래스2 여부**다.

폴더 간 중위수 폭 0.151 > 폴더 내 IQR 0.090이므로 그룹 차이 자체는 실재하지만, 그 그룹은
"누가 찍었나"가 아니다.

### 36-2. 그래서 진짜 원인은 규칙엔진이다

정답이 정확하다면 배율 1.17이 뜻하는 것은 하나뿐이다 — **규칙엔진 초안이 클래스2 케이스에서
치아 폭을 17% 과소추정한다.** 클래스2는 구치 관계가 어긋나 아치 형태가 달라지는데, 규칙엔진의
아치 템플릿은 그것을 반영하지 않는다. 라벨 문제가 아니라 **모델의 계통 오차**다.

섹션 35에 적은 "폭 라벨을 받을 때 누가 어떤 기준으로 찍었는지 함께 받아라"는 권고는
**철회한다.** 받아야 할 것은 주석자 정보가 아니라 **케이스의 부정교합 분류**다.

### 36-3. 평가를 쪼개면 부호가 뒤집힌다 — `_class2_scale_test.py` ⭐️

섹션 35-5의 −3.82%는 평가 집합이 기존 268건(클래스2 99 / 비클래스2 169)이라 **비클래스2가
2/3를 차지하는 평균**이었다. 같은 A/B를 그대로 두고 평가만 클래스로 쪼갰다(전역 배율 유지,
평가 집합은 여전히 기존 268건 고정, 신규는 train에만).

**클래스2 케이스(99건)에서 신규 116건은 전면적 이득이다:**

| 지표 | 평균 개선 | 개선 시드 | 유의 시드 |
|---|---:|---:|---:|
| 위치 | **+4.37%** | 4/4 | **4/4** |
| 어금니 위치 | **+6.78%** | 4/4 | **4/4** |
| 최말단 위치 | **+6.97%** | 4/4 | **4/4** |
| 치아별 길이 | **+2.58%** | 4/4 | 0/4 |
| **TZL 총합** | **+12.46%** | 4/4 | **4/4** |

**비클래스2 케이스(169건)에서는 손해다:**

| 지표 | 평균 | 개선 시드 | 유의 시드 |
|---|---:|---:|---:|
| 위치 | −0.35% | 1/4 | 0/4 |
| 어금니 | −2.77% | 0/4 | 4/4 |
| 최말단 | −3.22% | 0/4 | 4/4 |
| 치아별 길이 | **−8.37%** | 0/4 | 4/4 |
| TZL 총합 | −8.79% | 0/4 | 3/4 |

**섹션 35의 "길이 악화"는 클래스2 정답이 비클래스2 케이스로 번진 것이었다.** 길이가
나빠진 게 아니라, 모델이 클래스2에서 옳게 배운 "더 긴 폭"을 비클래스2에도 적용한 것이다.
정답 쪽 문제가 아니라 **모델이 케이스를 구분하지 못하는 문제**다.

### 36-4. 배율을 2개로 나누는 것으로는 안 된다

"클래스2 여부로 배율을 2개 쓰면 되나"를 실측했다. 배율은 각 폴드 train에서만 산출
(test 정답 누출 없음), 클래스2 1.0353 / 나머지 1.0036으로 갈렸다.

| 지표 | 전역 배율 1개(35-7) | **배율 2개** |
|---|---:|---:|
| 위치 | +1.42% | +1.42% (유의 2/4로 강화) |
| 치아별 길이 | −3.82% | **−3.72%** (여전히 4/4 유의 악화) |

**거의 그대로다.** 배율은 선분을 중점 기준으로 늘리는 **사후 스칼라**라서, 모델이 이미
학습해 버린 "치아별 폭 예측"의 계통 편향을 되돌리지 못한다. 고쳐야 하는 곳은 배율이 아니라
**모델 입력(특징)에 클래스2 정보가 없다는 것**이다.

### 36-5. 그래서 결론이 바뀐다

- 신규 116건은 **"좌표는 이득, 폭은 손해"인 교환이 아니다.** 클래스2에서는 **전 지표 이득**
  (TZL +12.5%)이고, 비클래스2에서 손해다. 데이터가 아니라 **적용 범위**의 문제다.
- 다음 수순의 **우선순위가 바뀐다.** 종전 1순위였던 EZ 라벨 확충보다, **클래스 정보를 모델
  입력에 넣는 것**이 먼저다. 라벨 추가 0건으로 클래스2 99건 + 신규 116건 = 215건의 이득을
  비클래스2로 새지 않게 막을 수 있다.
- 사후 배율 계열(전역 1개, 클래스별 2개)은 둘 다 실패했다. **특징 추가 또는 클래스별 모델**로
  가야 한다.

### 변경 이유
- 사용자가 정답의 신뢰도를 알려줬고, 그 전제에서는 기존 진단이 성립하지 않았다. 추측으로
  넘기지 않고 폴더별로 분해해 실측했다.
- 섹션 35를 지우지 않은 이유: 측정값은 유효하고 재현 가능하다. 틀린 것은 원인 귀속이므로
  **정정 섹션을 덧붙여 사고 경로를 남긴다.**

### 검증 결과
- 필요 폭 배율은 주석자가 아니라 클래스2 여부로 갈린다(담당자 다른 D·E가 CI 겹침)
- 클래스2 평가: 위치 +4.37% / 어금니 +6.78% / TZL +12.46%, 전부 4/4 시드 유의
- 비클래스2 평가: 길이 −8.37% / TZL −8.79%, 4/4 시드 유의 악화
- 배율 2개 분리로는 회복 안 됨(길이 −3.72%, 여전히 4/4 유의)
- 코드·모델 변경 없음. 운영 HTML SHA `6ee35113…712197` / 89,330 바이트 불변

### 남은 리스크
- **비클래스2 케이스의 폭 성능은 실제로 떨어진 상태다**(현재 임베드된 연구용 HTML 기준).
  클래스 정보를 넣기 전까지는 이 상태가 유지된다. 임상 사용 금지 전제가 계속 유효하다.
- 클래스2 판정을 **라벨 폴더 출처로 대리**했다. 폴더가 곧 임상 분류라는 가정이며, 원장 확인이
  필요하다. 실제로 쓰려면 케이스별 분류가 데이터에 있어야 한다(현재 없음).
- A_width_1st는 n=4로 통계가 없다. 이 코호트는 결론에 쓰지 않았다.
- 여러 폴더가 같은 이미지를 주석한 54건은 코호트 특정 불가로 제외했다. 클래스 분포가
  치우쳤을 수 있다.
- 클래스2 이득(+12.5%)이 "클래스2라서"인지 "그 케이스들이 규칙엔진 초안이 나빠서 개선 여지가
  컸기 때문"인지는 아직 분리하지 않았다. 초안 오차가 실제로 더 크다(35-6).

### 다음 수순 (우선순위 변경)
1. **클래스 정보를 폭 모델 입력에 추가** — 신규 1순위. 라벨 0건, 이득 대상 215건.
   특징 벡터에 분류 지시자를 넣거나 클래스별 모델로 분리한다. 사후 배율은 이미 기각됐다.
2. **케이스별 부정교합 분류 확보(원장 확인)** — 1번의 전제. 지금은 폴더 출처가 유일한 대리값.
3. EZ 라벨 100~200건 — 여전히 유효하지만 이제 2순위 이후.
4. 어금니 연구 성과의 운영 승격 — 독립 검증 + 사람 승인 필요.
"""


def main() -> None:
    raw = CONVERSATION.read_bytes()
    if not raw.endswith(b"\n"):
        raise SystemExit("conversation.md does not end with a newline")
    if b"## 36." in raw:
        raise SystemExit("section 36 already present - refusing to duplicate")

    body = SECTION.replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8")
    CONVERSATION.write_bytes(raw + body)

    after = CONVERSATION.read_bytes()
    if b"\r\r\n" in after:
        raise SystemExit("found CR CR LF - double conversion happened")

    production_sha = hashlib.sha256(PRODUCTION.read_bytes()).hexdigest()
    if production_sha != PRODUCTION_SHA:
        raise SystemExit("production HTML changed - must never happen")

    crlf, lf = bytes([13, 10]), bytes([10])
    print(f"conversation.md: {len(raw)} -> {len(after)} bytes")
    print(f"crlf lines: {raw.count(crlf)} -> {after.count(crlf)}")
    print(f"total lines: {raw.count(lf)} -> {after.count(lf)}")
    print(f"production sha unchanged: {production_sha[:12]}...")


if __name__ == "__main__":
    main()
